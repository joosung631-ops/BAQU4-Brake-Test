async function gpsBagResultsBrowserCases() {
  const get=id=>document.getElementById(id), canvas=get('gps-live-canvas');
  const assert=(value,message)=>{if(!value)throw Error(message);};
  const wait=async predicate=>{for(let i=0;i<500;i++){if(predicate())return;await new Promise(r=>setTimeout(r,20));}throw Error('Timeout: '+get('bag-status').textContent+' / '+get('gps-live-status').textContent);};
  const select=async bag=>{get('bag-select').value=bag;get('bag-select').dispatchEvent(new Event('change'));};
  const emit=(points,reset=false)=>window.fixtureGPS.emit(points,reset);
  const point=(t,lat,lon)=>({t,lat,lon,status:0,quality:4});
  await wait(()=>get('bag-select').options.length===4);
  assert(window.fixtureGPS.sockets.length===1,'duplicate script must not open two GPS sockets');
  emit([point(1,37,127)]);
  assert(canvas.dataset.pointCount==='1','unchecked mode accumulates live GPS');
  get('bag-results-only').click();
  get('bag-play').click();
  assert(window.fixtureGPS.plays===0,'play must wait for full GPS preparation');
  await wait(()=>window.fixtureGPS.plays===1);
  assert(canvas.dataset.pointCount==='12001','all points must be visible before first replay fix');
  assert(canvas.dataset.currentLat==='','new playback clears the old position marker');
  assert(get('gps-live-clear').disabled,'clear must not erase fixed results');
  emit([point(100,37,127)]);
  const first=canvas.dataset.currentLat;
  emit([point(101,37.0001,127.0001)]);
  assert(canvas.dataset.currentLat!==first,'current marker moves with replay GPS');
  assert(canvas.dataset.pointCount==='12001','moving marker does not append full track dots');
  const before=canvas.dataset.currentLat;
  emit([point(999999,38,128)]);
  assert(canvas.dataset.currentLat===before,'unrelated GPS timestamps do not move the replay marker');
  emit([point(100,37,127)],true);
  assert(canvas.dataset.currentLat==='37'&&canvas.dataset.pointCount==='12001','loop/reset preserves the whole track and moves marker back');
  get('bag-results-only').click();
  assert(canvas.dataset.resultMode==='false'&&!get('gps-live-clear').disabled,'uncheck restores live display');
  emit([point(101,37.0001,127.0001)]);
  assert(canvas.dataset.pointCount==='2','live mode continues accumulating');
  get('bag-results-only').click();
  assert(canvas.dataset.pointCount==='12001','recheck immediately restores cached full results');
  get('bag-results-only').click();emit([point(101,37.0001,127.0001)],true);
  get('bag-results-only').click();
  assert(!get('gps-live-coordinates').textContent.includes('E 0.00 m'),'rechecking after a live origin reset keeps the full track coordinate frame');
  get('bag-stop').click();await wait(()=>!get('bag-select').disabled);
  await select('bag-b');
  await wait(()=>canvas.dataset.pointCount==='2'&&canvas.dataset.resultMode==='true');
  assert(canvas.dataset.currentLat==='','switching bag clears the old cursor');
  emit([point(200,36,126)]);
  assert(canvas.dataset.currentLat==='36','new bag uses its own marker');
  await select('no-gps');await wait(()=>canvas.dataset.pointCount==='0'&&canvas.dataset.resultMode==='true');
  assert(get('gps-live-status').textContent.includes('전체 0점'),'GPS-free bag is represented explicitly');
  await select('broken');await wait(()=>get('gps-live-status').textContent.includes('broken bag'));
  const plays=window.fixtureGPS.plays;get('bag-play').click();
  await wait(()=>get('bag-status').textContent.includes('broken bag'));
  assert(window.fixtureGPS.plays===plays&&!get('bag-play').disabled,'failed preparation prevents play and permits recovery');
  await select('bag-a');await wait(()=>canvas.dataset.pointCount==='12001');
  return 'PASS: full GPS preload, current marker, loops, toggling, bag switch, no GPS, load failure and recovery';
}
